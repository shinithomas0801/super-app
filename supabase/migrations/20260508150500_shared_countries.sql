ALTER TABLE education_module.universities
  ADD CONSTRAINT universities_country_id_fkey
  FOREIGN KEY (country_id) REFERENCES public.countries (id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS education_module_universities_country_idx
  ON education_module.universities (country_id);

